"""Builds the reading-check site (audit_site/) from the same items and page as the artifact version: lib/items.js (served by the API only
after login) and public/index.html (scripts/audit_page_template.html with server storage, scripts/audit_site_app.js)."""
import json
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]; S = ROOT / 'audit_site'
items = json.load(open(ROOT / 'work/audit/items_v1.json'))
(S / 'lib/items.js').write_text('// generated by scripts/12_audit_site.py from work/audit/items_v1.json\nexport const SET_VERSION = "v1";\n'
                                f'export const ITEMS = {json.dumps(items, ensure_ascii=False)};\n')
t = (ROOT / 'scripts/audit_page_template.html').read_text()
head, _ = t.split('<script>\nconst ITEMS = __ITEMS__;', 1)
head = head.replace('<meta name="claude:viewport-fit-sides" content="cover">\n', '')
title_end = head.index('\n') + 1
head = ('<!doctype html>\n<html lang="zh-CN">\n<head>\n<meta charset="utf-8">\n'
        '<meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover">\n<meta name="robots" content="noindex,nofollow">\n'
        + head[:title_end] + head[title_end:].replace('</style>\n', '.who{font-size:12px;color:var(--muted)}\n.login{max-width:420px;margin:12vh auto 0}\n'
        '.login input{font:inherit;font-size:18px;letter-spacing:.08em;width:100%;box-sizing:border-box;border:1px solid var(--line);border-radius:8px;padding:10px;background:var(--panel);color:var(--ink)}\n'
        'body{margin:0}\n[hidden]{display:none!important}\n</style>\n</head>\n<body>\n', 1))
head = head.replace('<header class="bar"><div class="in">', '<header class="bar" id="hdr" hidden><div class="in">')
head = head.replace('<button class="small" id="bGrid" type="button">目录</button>\n',
                    '<button class="small" id="bGrid" type="button">目录</button>\n  <span class="who" id="who"></span>\n  <button class="small" id="bLogout" type="button">退出</button>\n')
head = head.replace('<main class="wrap">\n', '''<main class="wrap">
  <section id="vLogin" class="stack login" hidden>
    <h1>变异关联判读核对</h1>
    <p class="lead">请输入访问码。登录后进度保存在服务器上，换设备用同一个访问码即可继续。</p>
    <input id="codeIn" autocomplete="off" autocapitalize="characters" spellcheck="false" placeholder="访问码" aria-label="访问码">
    <input id="nameIn" autocomplete="name" placeholder="姓名（可不填）" aria-label="姓名">
    <div class="row"><button class="pri" id="bLogin" type="button">登录</button><span class="notice" id="loginMsg"></span></div>
  </section>
''', 1)
head = head.replace('每次选择都会自动保存到云端，同时在本机留一份', '每次选择都会自动保存到服务器，同时在本机留一份')
for k in ('id="vIntro" class="stack"',):
    head = head.replace(k, k + ' hidden', 1)
app = (ROOT / 'scripts/audit_site_app.js').read_text()
(S / 'public/index.html').write_text(head + '<script>\n' + app + '</script>\n</body>\n</html>\n')
print('items', len(items), '| index.html', len((S / 'public/index.html').read_text()), 'chars')
